#!/usr/bin/env python3
"""Generate the shared QML palette from the authoritative visual tokens."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
tokens = json.loads((ROOT / 'docs/visual/tokens.json').read_text())
controls = json.loads((ROOT / 'docs/visual/controls.json').read_text())
tree = json.loads((ROOT / 'docs/visual/directory-tree.json').read_text())


def qt_color(value):
    """JSON uses CSS RGBA; QColor's eight-digit notation is ARGB."""
    return '#' + value[7:9] + value[1:7] if len(value) == 9 and value.startswith('#') else value


lines = ['// Generated by scripts/generate-qml-theme.py; edit tokens.json for palette changes.',
         'pragma Singleton', 'import QtQuick', '', 'QtObject {',
         '    property bool dark: false', '    property real fontScale: 1.0']
for key, value in tokens['light'].items():
    lines.append(f'    readonly property color {key}: dark ? "{qt_color(tokens["dark"][key])}" : "{qt_color(value)}"')
for key, value in tokens['type'].items():
    lines.append(f'    readonly property real {key}Size: {value} * fontScale')
for key, value in controls['light'].items():
    lines.append(f'    readonly property color {key}: dark ? "{qt_color(controls["dark"][key])}" : "{qt_color(value)}"')
for key, value in controls['size'].items():
    lines.append(f'    readonly property real {key}: {value} * fontScale')
for key, value in controls['motion'].items():
    if isinstance(value, int) and not isinstance(value, bool):
        lines.append(f'    readonly property int {key}: {value}')
for key, value in tree['geometry'].items():
    name = 'tree' + ''.join(word.title() for word in key.split('_'))
    lines.append(f'    readonly property real {name}: {value}')
for key, value in tree['colors']['light'].items():
    values = []
    for theme in ('light', 'dark'):
        color = tree['colors'][theme][key]
        if not color.startswith('#'):
            source_theme, color_key = color.split('.')
            color = tokens[source_theme][color_key]
        values.append(qt_color(color))
    name = 'tree' + ''.join(word.title() for word in key.split('_')) + 'Color'
    lines.append(f'    readonly property color {name}: dark ? "{values[1]}" : "{values[0]}"')
for name, value in [('gutter',24), ('gap',12), ('iconSize',20), ('controlRadius',tokens['radius']['control']),
                    ('panelRadius',tokens['radius']['panel']), ('buttonHeight',tokens['size']['button']),
                    ('toolbarButtonHeight',tokens['size']['toolbarButton']),
                    ('toolbarIconSize',tokens['size']['toolbarIcon']), ('toolbarRadius',tokens['radius']['toolbar']),
                    ('rowHeight',tokens['size']['row']), ('sidebarWidth',tokens['size']['sidebar']),
                    ('inspectorWidth',tokens['size']['inspector']),
                    ('inspectorCollapseWidth',tokens['size']['inspectorCollapseWidth'])]:
    lines.append(f'    readonly property int {name}: {value}')
lines += ['}', '']
output = '\n'.join(lines)
path = ROOT / 'apps/desktop/ui/Theme.qml'
if args.check:
    if path.read_text() != output:
        raise SystemExit('QML theme differs from source tokens; regenerate it')
else:
    path.write_text(output)
