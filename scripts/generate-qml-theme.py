#!/usr/bin/env python3
"""Generate the shared QML palette from the authoritative visual tokens."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
tokens = json.loads((ROOT / 'docs/visual/tokens.json').read_text())
controls = json.loads((ROOT / 'docs/visual/controls.json').read_text())
tree = json.loads((ROOT / 'docs/visual/directory-tree.json').read_text())
main = json.loads((ROOT / 'docs/visual/qt-main-reference.json').read_text())
layout = json.loads((ROOT / 'docs/visual/layout-scale.json').read_text())
welcome = json.loads((ROOT / 'docs/visual/welcome-reference.json').read_text())
about = json.loads((ROOT / 'docs/visual/about-reference.json').read_text())
settings = json.loads((ROOT / 'docs/visual/settings-reference.json').read_text())
preflight = json.loads((ROOT / 'docs/visual/preflight-reference.json').read_text())
password = json.loads((ROOT / 'docs/visual/password-reference.json').read_text())
result = json.loads((ROOT / 'docs/visual/result-reference.json').read_text())
main_scale = main['logical_width'] / main['source_window'][2]


def qt_color(value):
    """JSON uses CSS RGBA; QColor's eight-digit notation is ARGB."""
    return '#' + value[7:9] + value[1:7] if len(value) == 9 and value.startswith('#') else value


lines = ['// Generated by scripts/generate-qml-theme.py; edit tokens.json for palette changes.',
         'pragma Singleton', 'import QtQuick', '', 'QtObject {',
         '    property bool dark: false', '    property real fontScale: 1.0']
lines.append(f'    readonly property real mainDensity: {layout["main"]["density"]}')
lines += ['    // Converts legacy logical insets; never applies a rendering transform.',
          '    function mainUnits(value: real): real { return value * mainDensity; }']
for name, value in zip(['mainWindowWidth', 'mainWindowHeight'], layout['main']['logical_window']):
    lines.append(f'    readonly property int {name}: {value}')
for name, value in zip(['mainMinimumWidth', 'mainMinimumHeight'], layout['main']['minimum_window']):
    lines.append(f'    readonly property int {name}: {value}')
for key, value in welcome.items():
    if key != "schema_version" and isinstance(value, (int, float)):
        name = ''.join(part.title() for part in key.split('_'))
        lines.append(f'    readonly property real welcome{name}: {value}')
for key, value in about.items():
    if key != 'schema_version' and isinstance(value, (int, float)):
        name = ''.join(part.title() for part in key.split('_'))
        lines.append(f'    readonly property real about{name}: {value}')
for key in ['logical_width', 'content_inset', 'section_gap', 'row_gap', 'title_size',
            'body_size', 'note_size', 'maximum_height', 'theme_artwork_width', 'theme_artwork_height',
            'theme_card_gap', 'theme_card_vertical_inset', 'hero_artwork_size', 'hero_gap', 'compact_list_factor']:
    name = ''.join(part.title() for part in key.split('_'))
    lines.append(f'    readonly property real settings{name}: {settings[key]}')
for key in ['logical_width', 'maximum_height', 'content_inset', 'section_gap', 'title_size',
            'body_size', 'note_size', 'count_size', 'card_radius', 'card_inset']:
    value = preflight[key]
    if isinstance(value, (int, float)):
        name = 'preflight' + ''.join(part.title() for part in key.split('_'))
        scale = ' * fontScale' if key.endswith('_size') else ''
        lines.append(f'    readonly property real {name}: {value}{scale}')
for key, value in layout['operation']['logical_widths'].items():
    identifier = ''.join(part.title() for part in key.split('-'))
    lines.append(f'    readonly property int operation{identifier}Width: {value}')
for key, value in layout['operation']['adding'].items():
    identifier = ''.join(part.title() for part in key.split('_'))
    lines.append(f'    readonly property real operationAdding{identifier}: {value}')
for key, value in password.items():
    if key != 'schema_version' and isinstance(value, (int, float)):
        name = 'password' + ''.join(part.title() for part in key.split('_'))
        scale = ' * fontScale' if key.endswith('_size') else ''
        lines.append(f'    readonly property real {name}: {value}{scale}')
lines.append(f'    readonly property real operationExtractDensity: {layout["operation"]["extract_density"]}')
lines.append(f'    readonly property real operationProgressDensity: {layout["operation"]["progress_density"]}')
lines.append(f'    readonly property real operationCreateDensity: {layout["operation"]["create_density"]}')
for key, value in layout['operation']['confirmation'].items():
    scale = ' * fontScale' if key.endswith('Size') else ''
    lines.append(f'    readonly property real confirmation{key[0].upper() + key[1:]}: {value}{scale}')
for key, value in layout['operation']['footer'].items():
    lines.append(f'    readonly property real operationFooter{key[0].upper() + key[1:]}: {value} * fontScale')
for key, value in layout['operation']['controls'].items():
    lines.append(f'    readonly property real operationControl{key[0].upper() + key[1:]}: {value}')
for key, value in layout['operation']['components'].items():
    suffix = ' * fontScale' if key.endswith('Size') else ''
    lines.append(f'    readonly property real operation{key[0].upper() + key[1:]}: {value}{suffix}')
for key in ['title_size', 'subtitle_size', 'body_size', 'section_size', 'note_size', 'count_size',
            'card_radius', 'card_inset', 'card_gap', 'row_height', 'details_height', 'client_height']:
    name = 'operationResult' + ''.join(word.title() for word in key.split('_'))
    scale = ' * fontScale' if key.endswith('_size') else ''
    lines.append(f'    readonly property real {name}: {result[key]}{scale}')
for key, value in tokens['light'].items():
    lines.append(f'    readonly property color {key}: dark ? "{qt_color(tokens["dark"][key])}" : "{qt_color(value)}"')
for key, value in tokens['type'].items():
    lines.append(f'    readonly property real {key}Size: {value} * fontScale')
    if key not in main['source_type']:
        lines.append(f'    readonly property real main{key[0].upper() + key[1:]}Size: {int(value * layout["main"]["density"] + .5)} * fontScale')
for key, value in controls['light'].items():
    lines.append(f'    readonly property color {key}: dark ? "{qt_color(controls["dark"][key])}" : "{qt_color(value)}"')
for key, value in controls['size'].items():
    lines.append(f'    readonly property real {key}: {value} * fontScale')
for key, value in controls['shadow'].items():
    lines.append(f'    readonly property real menuShadow{key[0].upper() + key[1:]}: {value}')
for key, value in controls['motion'].items():
    if isinstance(value, int) and not isinstance(value, bool):
        lines.append(f'    readonly property int {key}: {value}')
for key, value in tree['geometry'].items():
    name = 'tree' + ''.join(word.title() for word in key.split('_'))
    lines.append(f'    readonly property real {name}: {value}')
for key, value in tree['colors']['light'].items():
    values = []
    for theme in ('light', 'dark'):
        color = tree['colors'][theme][key]
        if not color.startswith('#'):
            source_theme, color_key = color.split('.')
            color = tokens[source_theme][color_key]
        values.append(qt_color(color))
    name = 'tree' + ''.join(word.title() for word in key.split('_')) + 'Color'
    lines.append(f'    readonly property color {name}: dark ? "{values[1]}" : "{values[0]}"')
for name, value in [('gutter',24), ('gap',12), ('iconSize',20), ('controlRadius',tokens['radius']['control']),
                    ('panelRadius',tokens['radius']['panel']), ('buttonHeight',tokens['size']['button']),
                    ('toolbarButtonHeight',tokens['size']['toolbarButton']),
                    ('toolbarIconSize',tokens['size']['toolbarIcon']), ('toolbarRadius',tokens['radius']['toolbar']),
                    ('rowHeight',tokens['size']['row']), ('sidebarWidth',tokens['size']['sidebar']),
                    ('inspectorWidth',tokens['size']['inspector']),
                    ('inspectorCollapseWidth',tokens['size']['inspectorCollapseWidth'])]:
    lines.append(f'    readonly property real {name}: {value}')
lines.append(f'    readonly property real mainControlRadius: {tokens["radius"]["control"] * layout["main"]["density"]}')
lines.append(f'    readonly property real mainToolbarRadius: {tokens["radius"]["toolbar"] * layout["main"]["density"]}')
for key, value in layout['main']['interaction'].items():
    lines.append(f'    readonly property real main{key[0].upper() + key[1:]}: {value}')
for key, value in layout['main']['titlebar'].items():
    if key.startswith('tab_') and key not in ('tab_height', 'tab_vertical_inset', 'tab_radius'):
        name = 'main' + ''.join(part.title() for part in key.split('_'))
        lines.append(f'    readonly property real {name}: {value}')
for key, value in main['source_geometry'].items():
    name = 'main' + key[0].upper() + key[1:]
    converted = value * main_scale
    if key == 'toolbarHeight':
        # Round shared boundaries, not every band independently: avoid accumulated drift.
        converted = round((main['source_geometry']['titleHeight'] + value) * main_scale) - round(main['source_geometry']['titleHeight'] * main_scale)
    elif key == 'statusHeight':
        converted = layout['main']['logical_window'][1] - round(main['anchors']['browserStatus'][1] * main_scale)
    title = layout['main']['titlebar']
    converted = {'titleHeight': title['height'], 'tabHeight': title['tab_height'],
                 'tabTopInset': title['tab_vertical_inset']}.get(key, converted)
    lines.append(f'    readonly property real {name}: {converted:.8f}')
for key, value in main['source_type'].items():
    name = 'main' + key[0].upper() + key[1:] + 'Size'
    lines.append(f'    readonly property real {name}: {int(value * main_scale + .5)} * fontScale')
lines += ['}', '']
output = '\n'.join(lines)
path = ROOT / 'apps/desktop/ui/Theme.qml'
if args.check:
    if path.read_text() != output:
        raise SystemExit('QML theme differs from source tokens; regenerate it')
else:
    path.write_text(output)
