#!/usr/bin/env python3
"""Share the product language catalogs with the HTML settings design."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
catalogs={locale:json.loads((ROOT/'resources/i18n'/f'{locale}.json').read_text(encoding='utf-8')) for locale in ['zh-CN','en-US']}
output='// Generated by scripts/generate-ui-messages.py; edit resources/i18n/*.json.\nwindow.XDZIP_UI_MESSAGES = '+json.dumps(catalogs,ensure_ascii=False,separators=(',',':'))+';\n'
path=ROOT/'design/html/ui-messages.js'
if args.check:
    if not path.exists() or path.read_text(encoding='utf-8')!=output: raise SystemExit('Stale HTML UI language catalogs')
else:path.write_text(output,encoding='utf-8')
print('HTML settings language catalogs match product resources')

# Native file-manager hosts use the same catalog without loading Qt.
keys = ['shell.finderHandoffFailed','shell.finderRequestRejected','shell.title','shell.addNamed','shell.create','shell.separateZip','shell.extractHere',
        'shell.extractSmart','shell.extractSeparate','shell.extractTo']
lines = ['// Generated by scripts/generate-ui-messages.py; edit resources/i18n/*.json.',
         '#pragma once', '#include <string>', 'namespace xdzip_shell {',
         'inline std::string text(bool english, const std::string &id) {']
for key in keys:
    en = json.dumps(catalogs['en-US']['messages'][key], ensure_ascii=False)
    zh = json.dumps(catalogs['zh-CN']['messages'][key], ensure_ascii=False)
    lines.append('    if (id == '+json.dumps(key)+') return english ? '+en+' : '+zh+';')
lines += ['    return id;', '}', '}', '']
native = '\n'.join(lines)
native_path = ROOT/'apps/desktop/shell/NativeMessages.h'
if args.check:
    if not native_path.exists() or native_path.read_text(encoding='utf-8') != native:
        raise SystemExit('Stale native shell language catalogs')
else:
    native_path.write_text(native, encoding='utf-8')
