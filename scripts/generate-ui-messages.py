#!/usr/bin/env python3
"""Generate native file-manager messages from product language catalogs."""
import argparse
import json
from pathlib import Path
from ui_languages import load_languages
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
catalogs = {}
for language in load_languages()['languages']:
    locale = language['id']
    catalog = ROOT/'resources/i18n'/f'{locale}.json'
    if catalog.is_file():
        catalogs[locale] = json.loads(catalog.read_text(encoding='utf-8'))
# Native file-manager hosts use the same catalog without loading Qt.
keys = ['shell.finderHandoffFailed','shell.finderRequestRejected','shell.title','shell.addNamed','shell.create','shell.separateZip','shell.extractHere',
        'shell.extractSmart','shell.extractSeparate','shell.extractTo']
lines = [
    '// Generated by scripts/generate-ui-messages.py; edit resources/i18n/*.json.',
    '#pragma once', '#include "../LanguageSelection.h"', 'namespace xdzip_shell {',
    'inline std::string text(std::string_view locale, std::string_view id) {',
    '    struct Message { std::string_view locale, id, value; };',
    '    static constexpr Message messages[] = {',
]
for locale, catalog in catalogs.items():
    for key in keys:
        value = catalog['messages'][key]
        lines.append('        {' + ', '.join(json.dumps(field, ensure_ascii=False)
                                             for field in (locale, key, value)) + '},')
lines += [
    '    };',
    '    std::string_view fallback = id;',
    '    for (const auto &message : messages) {',
    '        if (message.id != id)',
    '            continue;',
    '        if (message.locale == locale)',
    '            return std::string(message.value);',
    '        if (message.locale == xdzip_i18n::defaultLanguage)',
    '            fallback = message.value;',
    '    }',
    '    return std::string(fallback);',
    '}', '}', '',
]
native = '\n'.join(lines)
native_path = ROOT/'apps/desktop/shell/NativeMessages.h'
if args.check:
    if not native_path.exists() or native_path.read_text(encoding='utf-8') != native:
        raise SystemExit('Stale native shell language catalogs')
else:
    native_path.write_text(native, encoding='utf-8')
