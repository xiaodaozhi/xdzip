#!/usr/bin/env python3
"""Synchronize Cargo and HTML from VERSION.json; --check never writes files."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def version_info():
    info = json.loads((ROOT / 'VERSION.json').read_text())
    if not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', info['version']):
        raise ValueError('Version must be major.minor.patch without leading zeros')
    if any(int(n) > 65535 for n in info['version'].split('.')):
        raise ValueError('Version components must fit Windows VERSIONINFO')
    channels = {'development': 'dev', 'alpha': 'alpha', 'beta': 'beta', 'rc': 'rc', 'stable': ''}
    if info['channel'] not in channels or type(info['build']) is not int or not 1 <= info['build'] <= 65535:
        raise ValueError('Invalid channel or build number')
    suffix = channels[info['channel']]
    number = info.get('prerelease_number', info['build'])
    if type(number) is not int or not 1 <= number <= 65535 or ('prerelease_number' in info and not suffix):
        raise ValueError('Invalid prerelease number')
    info['display_version'] = info['version'] + (f'-{suffix}.{number}' if suffix else '')
    return info

def set_version(source, section, value):
    pattern = r'(?ms)(^\[' + re.escape(section) + r'\]\n)(.*?)(?=^\[|\Z)'
    def update(match):
        body = match[2]
        if re.search(r'(?m)^version(?:\.workspace)?\s*=', body):
            body = re.sub(r'(?m)^version(?:\.workspace)?\s*=.*$', value, body, count=1)
        else:
            body = value + '\n' + body
        return match[1] + body
    result, count = re.subn(pattern, update, source, count=1)
    if count != 1:
        raise ValueError(f'Missing [{section}] section')
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    info = version_info()
    updates = {}
    root = ROOT / 'Cargo.toml'
    updates[root] = set_version(root.read_text(), 'workspace.package', f'version = "{info["display_version"]}"')
    for path in list((ROOT / 'crates').glob('*/Cargo.toml')) + list((ROOT / 'tools').glob('*/Cargo.toml')):
        updates[path] = set_version(path.read_text(), 'package', 'version.workspace = true')
    updates[ROOT / 'design/html/version.js'] = '// Generated by scripts/sync-version.py from VERSION.json.\nwindow.XDZIP_VERSION = Object.freeze(' + json.dumps(info, separators=(',', ':')) + ');\n'
    for path, expected in updates.items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f'Stale version metadata: {path.relative_to(ROOT)}')
        elif not path.exists() or path.read_text() != expected:
            path.write_text(expected)
    print('Product, Cargo and HTML versions match:', info['display_version'])

if __name__ == '__main__':
    main()
