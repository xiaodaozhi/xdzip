# scripts/generate-file-icons.py

"""Generate identical extension hints for Qt and the HTML design."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    check = parser.parse_args().check
    spec = json.loads((ROOT / 'docs/visual/file-types.json').read_text(encoding='utf-8'))
    seen = set()
    for extensions in spec['categories'].values():
        assert not seen.intersection(extensions), 'Ambiguous file extension hint'
        seen.update(extensions)
    branches = [(json.dumps(extensions), json.dumps(icon)) for icon, extensions in spec['categories'].items()]
    selector = '\n            : '.join(f'{extensions}.includes(suffix) ? {icon}' for extensions, icon in branches)
    selection = f'directory ? "folder" : {selector}\n            : "file-text"'
    qml = ('// apps/desktop/ui/AssetLibrary.qml\n\n'
           '// Generated by scripts/generate-file-icons.py from docs/visual/file-types.json.\n'
           'pragma Singleton\nimport QtQuick\n\nQtObject {\n'
           '    // Extension hints do not assert content identity or codec support.\n'
           '    function iconKind(name: string, directory: bool): string {\n'
           '        const suffix = name.toLowerCase().split(".").pop();\n'
           f'        return {selection};\n    }}\n'
           '    function fileIcon(name: string, directory: bool, large: bool): string {\n'
           '        return "qrc:/xdzip/assets/" + (Theme.dark ? "dark/" : "light/") + iconKind(name, directory) + (large ? "-large" : "") + ".png";\n'
           '    }\n}\n')
    app = ROOT / 'design/html/app.js'
    source = app.read_text(encoding='utf-8')
    function = ('function fileIcon(e) {\n'
                '    const suffix = e.name.toLowerCase().split(".").pop();\n'
                f'    return {selection.replace("directory ?", "e.folder ?")};\n}}')
    html = re.sub(r'function fileIcon\(e\) \{.*?\n\}', lambda _: function, source, count=1, flags=re.S)
    for path, expected in [(ROOT / 'apps/desktop/ui/AssetLibrary.qml', qml), (app, html)]:
        if check:
            assert path.read_text(encoding='utf-8') == expected, f'Stale file icon selector: {path.name}'
        else:
            path.write_text(expected, encoding='utf-8', newline='\n')
    print(f'File icon hints: {len(seen)} extensions, Qt and HTML agree')


if __name__ == '__main__':
    main()
