#!/usr/bin/env python3
"""Exercise the design prototype in Chromium; archive operations remain simulated.

Requires Playwright and a Chromium executable. Screenshots and reports are written
under dist/prototype-review. This is not a product codec or platform safety test.
"""
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from threading import Thread
import json
import os
from playwright.sync_api import sync_playwright, expect

PROJECT = Path(__file__).resolve().parents[1]
ROOT = PROJECT / 'design/prototype'
OUTPUT = PROJECT / 'dist/prototype-review'
OUTPUT.mkdir(parents=True, exist_ok=True)
if os.environ.get('XDZIP_FONTCONFIG_FILE'):
    os.environ['FONTCONFIG_FILE'] = os.environ['XDZIP_FONTCONFIG_FILE']

class QuietHandler(SimpleHTTPRequestHandler):
    def log_message(self, *_args):
        pass

server = ThreadingHTTPServer(('127.0.0.1', 0), partial(QuietHandler, directory=str(ROOT)))
Thread(target=server.serve_forever, daemon=True).start()
url = f'http://127.0.0.1:{server.server_port}/'
checks, errors, external = [], [], []

def record(name):
    checks.append(name)

def screenshot(page, name):
    page.screenshot(path=str(OUTPUT / f'{name}.png'), full_page=True)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('XDZIP_CHROMIUM', '/usr/bin/chromium'), headless=True, args=['--no-sandbox', '--disable-dev-shm-usage'])
    context = browser.new_context(viewport={'width': 1500, 'height': 1000}, locale='zh-CN')
    def route_request(route):
        if route.request.url.startswith(url):
            route.continue_()
        else:
            external.append(route.request.url)
            route.abort()
    context.route('**/*', route_request)
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    try:
        page.goto(url)
        expect(page.locator('#file-rows tr')).to_have_count(9)
        expect(page.locator('#extract-label')).to_have_text('全部解压')
        page.locator('[data-id=lake] input').check()
        page.locator('[data-id=sunrise] input').check()
        page.locator('[data-id=guide] input').check()
        expect(page.locator('#selection-status')).to_contain_text('27.4 MB')
        record('Three-file selection totals 27.4 MB')
        screenshot(page, '01-main-light')
        page.locator('#theme').click()
        screenshot(page, '02-main-dark')
        page.locator('#theme').click()
        page.locator('#extract').click()
        expect(page.locator('#target-preview')).to_have_text('最终位置：下载 / 北境旅行')
        page.locator('#target-base').fill('下载 / 北境旅行')
        expect(page.locator('#target-preview')).to_have_text('最终位置：下载 / 北境旅行')
        record('Same-name output folder is not duplicated')
        screenshot(page, '03-extract-confirm')
        page.locator('#start-extract').click()
        expect(page.locator('#progress-value')).to_be_visible()
        page.wait_for_timeout(1100)
        screenshot(page, '04-progress')
        expect(page.locator('.result-hero h2')).to_have_text('解压完成', timeout=12000)
        expect(page.locator('.result-counts b').nth(0)).to_have_text('3')
        screenshot(page, '05-success')
        page.locator('.modal-footer [data-close]').click()
        record('Selected extraction reaches a consistent success summary')
        page.locator('#search').fill('行程')
        expect(page.locator('#file-rows tr')).to_have_count(1)
        expect(page.locator('#extract-label')).to_have_text('全部解压')
        page.locator('#extract').click()
        expect(page.locator('.scope-box')).to_contain_text('30 项')
        page.keyboard.press('Escape')
        page.locator('#extract-menu-button').click()
        page.locator('[data-extract=results]').click()
        expect(page.locator('.scope-box')).to_contain_text('当前搜索结果')
        expect(page.locator('.scope-box')).to_contain_text('12.8 MB')
        page.keyboard.press('Escape')
        record('All-archive and explicit search-result scopes remain distinct')
        page.locator('#scenario').select_option('conflict')
        page.locator('#start-extract').click()
        expect(page.locator('#skip-conflict')).to_be_focused()
        screenshot(page, '06-conflict')
        page.locator('#rename-conflict').click()
        expect(page.locator('.result-hero h2')).to_have_text('解压完成', timeout=12000)
        expect(page.locator('#modal')).to_contain_text('行程手册 (2).pdf')
        page.locator('.modal-footer [data-close]').click()
        record('Conflict defaults to a non-destructive action; rename is reported')
        page.locator('#scenario').select_option('permission')
        expect(page.locator('#start-extract')).to_be_disabled()
        screenshot(page, '07-permission')
        page.locator('#change-target').click()
        expect(page.locator('#start-extract')).to_be_enabled()
        page.keyboard.press('Escape')
        record('Unwritable destination blocks submission until changed')
        page.locator('#scenario').select_option('disk')
        page.locator('#start-extract').click()
        expect(page.locator('.result-hero h2')).to_have_text('部分文件未能完成', timeout=12000)
        expect(page.locator('.result-counts b').nth(0)).to_have_text('2')
        expect(page.locator('.result-counts b').nth(2)).to_have_text('1')
        screenshot(page, '08-partial-failure')
        page.locator('#retry-result').click()
        expect(page.locator('.scope-box')).to_contain_text('失败或未完成项')
        expect(page.locator('.scope-box')).to_contain_text('1 项')
        page.keyboard.press('Escape')
        record('Partial failure retains two files and replans only the failed item')
        page.locator('#scenario').select_option('cancel')
        page.locator('#start-extract').click()
        page.wait_for_timeout(800)
        page.locator('#cancel-task').click()
        expect(page.locator('#cancel-task')).to_be_disabled()
        expect(page.locator('.result-hero h2')).to_have_text('任务已取消')
        screenshot(page, '09-cancelled')
        page.keyboard.press('Escape')
        record('Cancellation passes through stopping before a terminal summary')
        page.locator('#scenario').select_option('normal')
        page.locator('#create').click()
        screenshot(page, '10-create')
        page.locator('#create-format').select_option('tar')
        expect(page.locator('#level-group')).to_be_hidden()
        expect(page.locator('#method-group')).to_be_hidden()
        expect(page.locator('#create-name')).to_have_value('旅行资料.tar')
        page.locator('#create-format').select_option('tar.gz')
        expect(page.locator('#level-group')).to_be_visible()
        page.locator('#clear-input').click()
        expect(page.locator('#start-create')).to_be_disabled()
        page.locator('#add-input').click()
        expect(page.locator('#start-create')).to_be_enabled()
        page.locator('#start-create').click()
        expect(page.locator('.result-hero h2')).to_have_text('压缩文件已创建', timeout=12000)
        expect(page.locator('.result-counts b').nth(0)).to_have_text('1')
        page.keyboard.press('Escape')
        record('Format capabilities update fields; empty input blocks creation; creation publishes one archive')
        for scene, text in [('empty','这个压缩文件没有内容'),('noresult','没有找到匹配项'),('unsupported','暂不支持此加密方式'),('damaged','无法读取压缩文件')]:
            page.locator('#scenario').select_option(scene)
            expect(page.locator('#empty-state h2')).to_have_text(text)
            screenshot(page, 'state-'+scene)
        record('Empty, no-result, unsupported and damaged states are distinct')
        page.locator('#scenario').select_option('normal')
        page.locator('[data-id=photos]').dblclick()
        expect(page.locator('#file-rows tr')).to_have_count(12)
        record('Folder navigation uses the actual fixture children')
        page.locator('#settings').click()
        page.locator('#setting-theme').select_option('dark')
        expect(page.locator('html')).to_have_attribute('data-theme','dark')
        screenshot(page, '11-settings-dark')
        page.keyboard.press('Escape')
        page.locator('#theme').click()
        page.set_viewport_size({'width':390,'height':844})
        page.locator('#scenario').select_option('normal')
        screenshot(page, '12-mobile-browser')
        page.locator('[data-id=lake] input').check()
        page.locator('[data-id=sunrise] input').check()
        page.locator('[data-id=guide] input').check()
        page.locator('#extract').click()
        screenshot(page, '13-mobile-extract')
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1')
        assert page.locator('#modal').evaluate('(n) => n.scrollWidth <= n.clientWidth + 1')
        record('390 px mobile review has no horizontal page or dialog overflow')
        page.keyboard.press('Escape')
        page.set_viewport_size({'width':1500,'height':1000})
        page.locator('#scenario').select_option('conflict')
        page.locator('#start-extract').click()
        page.locator('#skip-conflict').click()
        expect(page.locator('.result-hero h2')).to_have_text('解压完成', timeout=12000)
        expect(page.locator('.result-counts b').nth(0)).to_have_text('2')
        expect(page.locator('.result-counts b').nth(1)).to_have_text('1')
        page.keyboard.press('Escape')
        record('Skip preserves the existing file and reports two successes plus one skip')
        page.locator('#scenario').select_option('source')
        page.locator('#start-extract').click()
        expect(page.locator('.result-hero h2')).to_have_text('源文件已发生变化', timeout=12000)
        expect(page.locator('#reopen-result')).to_be_visible()
        screenshot(page, '14-source-changed')
        page.keyboard.press('Escape')
        record('Changed archive source stops the task and requires reopening')
        page.locator('#scenario').select_option('normal')
        page.locator('#create').click()
        page.locator('summary').click()
        page.locator('#create-existing').check()
        page.locator('#start-create').click()
        expect(page.locator('#cancel-create-overwrite')).to_be_focused()
        screenshot(page, '15-create-overwrite')
        page.locator('#confirm-create-overwrite').click()
        page.locator('#cancel-task').click()
        expect(page.locator('.result-hero h2')).to_have_text('任务已取消')
        expect(page.locator('.result-counts b').nth(0)).to_have_text('0')
        expect(page.locator('.result-hero p')).to_contain_text('原有文件保持不变')
        page.keyboard.press('Escape')
        record('Creating over an existing archive requires explicit confirmation; cancelled creation publishes nothing')
        page.locator('#scenario').select_option('empty')
        expect(page.locator('#selection-status')).to_have_text('0 个文件 · 0 个文件夹')
        expect(page.locator('#tree')).not_to_contain_text('30')
        page.locator('#scenario').select_option('normal')
        page.locator('#search').evaluate("n => n.dispatchEvent(new CompositionEvent('compositionstart', {bubbles:true}))")
        page.locator('#search').fill('行程')
        expect(page.locator('#file-rows tr')).to_have_count(9)
        page.locator('#search').evaluate("n => n.dispatchEvent(new CompositionEvent('compositionend', {bubbles:true}))")
        expect(page.locator('#file-rows tr')).to_have_count(1)
        record('Search defers updates during IME composition; empty archives show consistent zero counts')
        # Check the distributable HTML itself, with every network request blocked.
        bundled = (PROJECT/'dist/xdzip-interactive-design.html').read_text()
        offline = context.new_page()
        offline.on('pageerror', lambda error: errors.append(str(error)))
        offline.route('**/*', lambda route: route.abort())
        offline.set_content(bundled)
        expect(offline.locator('#file-rows tr')).to_have_count(9)
        offline.locator('#create').click()
        expect(offline.locator('#start-create')).to_be_enabled()
        offline.close()
        record('Single-file distributable initializes and opens creation without network access')
        assert not errors, errors
        assert not external, external
    finally:
        (OUTPUT/'validation.json').write_text(json.dumps({'checks':checks,'page_errors':errors,'external_requests':external,'scope':'Simulated design interactions only'},ensure_ascii=False,indent=2)+'\n')
        browser.close()
        server.shutdown()
print(json.dumps({'passed':len(checks),'screenshots':len(list(OUTPUT.glob('*.png'))),'output':str(OUTPUT)},ensure_ascii=False))
