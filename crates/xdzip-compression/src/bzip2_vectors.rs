pub(super) enum Piece {
    Bytes(&'static [u8]),
    Zeros(usize),
}
pub(super) struct Fixture {
    pub(super) name: &'static str,
    pub(super) parts: &'static [Piece],
}
pub(super) fn bytes(fixture: &Fixture) -> Vec<u8> {
    let mut output = Vec::new();
    for piece in fixture.parts {
        match piece {
            Piece::Bytes(bytes) => output.extend_from_slice(bytes),
            Piece::Zeros(count) => output.resize(output.len() + count, 0),
        }
    }
    output
}

